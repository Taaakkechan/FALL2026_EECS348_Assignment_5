#include <iostream> // Provides console input and output.
#include <fstream> // Allows the program to read and write files.
#include <string> // Provides the string data type.
#include <cstdio> // Provides remove for deleting files.

using namespace std; // Avoids writing std:: before standard names.

const int GRID_SIZE = 9; // Stores the number of rows, columns, and digits.
const int BLOCK_SIZE = 3; // Stores the width and height of a block.
const int CELL_COUNT = GRID_SIZE * GRID_SIZE; // Stores the number of cells in a puzzle.

class SudokuSolver { // Defines an object that solves Sudoku puzzles.
private: // Keeps these members accessible only inside the class.
    int grid[GRID_SIZE][GRID_SIZE]; // Stores the 9x9 Sudoku grid.
    bool rowUsed[GRID_SIZE][GRID_SIZE + 1]; // Checkboxes for the digits used in each row, indexed by digit.
    bool colUsed[GRID_SIZE][GRID_SIZE + 1]; // Checkboxes for the digits used in each column, indexed by digit.
    bool blockUsed[GRID_SIZE][GRID_SIZE + 1]; // Checkboxes for the digits used in each 3x3 block, indexed by digit.
    string fileName; // Stores the current puzzle filename.
    int solutionCount; // Counts the solutions found.
    ofstream solutionFile; // Writes solutions as they are found, so none are kept in memory.

    bool findEmptyCell(int startCell, int &row, int &col) const { // Finds the next blank cell, starting at startCell.
        for (int cell = startCell; cell < CELL_COUNT; cell++) { // Checks each remaining cell.
            row = cell / GRID_SIZE; // Converts the cell number to a row.
            col = cell % GRID_SIZE; // Converts the cell number to a column.

            if (grid[row][col] == 0) { // Checks whether the cell is blank.
                return true; // Reports that a blank was found.
            } // Ends the blank-cell check.
        } // Ends the cell loop.

        return false; // Reports that no blank cells remain.
    } // Ends findEmptyCell.

    int blockIndex(int row, int col) const { // Numbers the 3x3 blocks 0 through 8.
        return (row / BLOCK_SIZE) * BLOCK_SIZE + (col / BLOCK_SIZE); // Combines the block's row and column.
    } // Ends blockIndex.

    bool isSafe(int row, int col, int digit) const { // Checks if a digit can fit.
        return !rowUsed[row][digit] && !colUsed[col][digit] && !blockUsed[blockIndex(row, col)][digit]; // Allows the digit if all three checkboxes are clear.
    } // Ends isSafe.

    void setUsed(int row, int col, int digit, bool used) { // Updates a digit's checkboxes.
        rowUsed[row][digit] = used; // Updates the row's checkbox.
        colUsed[col][digit] = used; // Updates the column's checkbox.
        blockUsed[blockIndex(row, col)][digit] = used; // Updates the block's checkbox.
    } // Ends setUsed.

    bool initialGridIsValid() { // Fills the checkboxes and checks for conflicts.
        for (int i = 0; i < GRID_SIZE; i++) { // Visits each row, column, and block.
            for (int digit = 1; digit <= GRID_SIZE; digit++) { // Visits each digit.
                rowUsed[i][digit] = false; // Clears the row's checkbox.
                colUsed[i][digit] = false; // Clears the column's checkbox.
                blockUsed[i][digit] = false; // Clears the block's checkbox.
            } // Ends the digit loop.
        } // Ends the clearing loop.

        for (int row = 0; row < GRID_SIZE; row++) { // Visits every row.
            for (int col = 0; col < GRID_SIZE; col++) { // Visits every column.
                int digit = grid[row][col]; // Saves the current cell value.

                if (digit == 0) { // Checks whether the cell is empty.
                    continue; // Skips empty cells.
                } // Ends the empty-cell check.

                if (!isSafe(row, col, digit)) { // Checks against the digits seen so far.
                    return false; // Rejects the invalid puzzle.
                } // Ends the conflict check.

                setUsed(row, col, digit, true); // Marks the starting digit as used.
            } // Ends the column loop.
        } // Ends the row loop.

        return true; // Accepts the puzzle's starting digits.
    } // Ends initialGridIsValid.

    void printGrid(ostream &out) const { // Prints the grid in the puzzle file format.
        for (int row = 0; row < GRID_SIZE; row++) { // Prints each row.
            for (int col = 0; col < GRID_SIZE; col++) { // Prints each cell.
                if (grid[row][col] == 0) { // Checks for an empty cell.
                    out << "_ "; // Prints an underscore for a blank.
                } else { // Handles cells containing digits.
                    out << grid[row][col] << " "; // Prints the digit.
                } // Ends the cell-value check.
            } // Ends the column loop.

            out << '\n'; // Moves to the next line without a slow flush.
        } // Ends the row loop.
    } // Ends printGrid.

    void printHeader() const { // Prints the filename and the unsolved puzzle.
        cout << "\n========================================\n"; // Prints a top divider.
        cout << "Puzzle file: " << fileName << '\n'; // Prints the filename.
        cout << "========================================\n"; // Prints a bottom divider.

        cout << "\nOriginal puzzle:\n"; // Labels the original grid.
        printGrid(cout); // Displays the unsolved puzzle.
    } // Ends printHeader.

    void reportSolution() { // Counts a completed grid and saves it.
        solutionCount++; // Counts the completed solution.
        cout << "\nSolution " << solutionCount << ":\n"; // Prints its number.
        printGrid(cout); // Prints the completed Sudoku grid.

        if (solutionCount > 1) { // Checks for an earlier solution in the file.
            solutionFile << '\n'; // Separates it from the previous solution.
        } // Ends the separator check.

        printGrid(solutionFile); // Writes the completed Sudoku grid.
    } // Ends reportSolution.

    void reportResult(bool validPuzzle) { // Prints and saves the final result.
        if (solutionCount == 0) { // Checks whether any solution was found.
            cout << "\nNo solution found."; // Reports that no solution exists.

            if (!validPuzzle) { // Checks whether the starting digits were the reason.
                cout << " Puzzle has conflicting starting digits."; // Explains why.
            } // Ends the invalid-puzzle check.

            cout << endl; // Ends the message.
            solutionFile << "No solution found.\n"; // Records that no solution exists.
        } else { // Handles puzzles with solutions.
            cout << "\nTotal solutions found: " << solutionCount << endl; // Prints the total.
            solutionFile << "Solutions found: " << solutionCount << '\n'; // Records the total.
        } // Ends the solution-count check.
    } // Ends reportResult.

    void solveRecursive(int startCell) { // Searches for every solution, skipping cells before startCell.
        int row; // Stores the next blank cell's row.
        int col; // Stores the next blank cell's column.

        if (!findEmptyCell(startCell, row, col)) { // Checks whether the grid is complete.
            reportSolution(); // Saves the completed grid.
            return; // Returns to search for other solutions.
        } // Ends the completed-grid check.

        for (int digit = 1; digit <= GRID_SIZE; digit++) { // Tries digits 1 through 9.
            if (isSafe(row, col, digit)) { // Checks whether the digit fits.
                grid[row][col] = digit; // Places the temporary digit.
                setUsed(row, col, digit, true); // Marks the digit as used.
                solveRecursive(row * GRID_SIZE + col + 1); // Recursively solves the remaining cells.
                grid[row][col] = 0; // Removes the digit to backtrack.
                setUsed(row, col, digit, false); // Clears the digit's checkboxes.
            } // Ends the valid-digit check.
        } // Ends the digit loop.
    } // Ends solveRecursive.

public: // Makes these members accessible outside the class.
    SudokuSolver() { // Creates and initializes a solver object.
        solutionCount = 0; // Starts the solution count at zero.

        for (int row = 0; row < GRID_SIZE; row++) { // Visits every row.
            for (int col = 0; col < GRID_SIZE; col++) { // Visits every column.
                grid[row][col] = 0; // Marks every cell as empty.
            } // Ends the column loop.
        } // Ends the row loop.
    } // Ends the constructor.

    bool loadFromFile(const string &name) { // Reads a puzzle from a file.
        fileName = name; // Saves the filename.
        ifstream inputFile(fileName); // Opens the puzzle file.

        if (!inputFile.is_open()) { // Checks whether the file opened.
            cerr << "Error: Could not open " << fileName << endl; // Prints an error.
            return false; // Reports that loading failed.
        } // Ends the file-opening check.

        int cellsRead = 0; // Counts the cells read, including any past the end of the grid.
        char character; // Stores each character read from the file.

        while (inputFile.get(character)) { // Reads one character at a time.
            if ((character >= '1' && character <= '9') || character == '_') { // Checks for a cell.
                if (cellsRead < CELL_COUNT) { // Keeps extra cells from overflowing the grid.
                    if (character == '_') { // Checks for a blank character.
                        grid[cellsRead / GRID_SIZE][cellsRead % GRID_SIZE] = 0; // Stores blanks as zero.
                    } else { // Handles digit characters.
                        grid[cellsRead / GRID_SIZE][cellsRead % GRID_SIZE] = character - '0'; // Converts the character to an integer.
                    } // Ends the cell conversion.
                } // Ends the grid-bounds check.

                cellsRead++; // Moves to the next cell.
            } else if (character != ' ' && character != '\t' && character != '\n' && character != '\r') { // Checks for invalid characters.
                cerr << "Error: Invalid character in " << fileName << endl; // Prints an error.
                return false; // Reports that loading failed.
            } // Ends the character check.
        } // Ends the file-reading loop.

        if (cellsRead != CELL_COUNT) { // Checks for exactly 81 cells.
            cerr << "Error: " << fileName << " must contain exactly " << CELL_COUNT << " cells; found " << cellsRead << "." << endl; // Explains the size error.
            return false; // Rejects the incorrectly sized puzzle.
        } // Ends the cell-count check.

        return true; // Reports that loading succeeded.
    } // Ends loadFromFile.

    bool solve(const string &outputName) { // Prints, solves, and saves the current puzzle.
        printHeader(); // Displays the filename and unsolved puzzle.

        solutionFile.open(outputName); // Creates the solution file.
        bool fileOpened = solutionFile.is_open(); // Records whether the file can be written.

        if (!fileOpened) { // Checks whether the file opened.
            cerr << "Error: Could not create " << outputName << endl; // Prints an error and keeps solving for the console.
        } // Ends the file-opening check.

        solutionCount = 0; // Resets the solution count.
        bool validPuzzle = initialGridIsValid(); // Checks for conflicting starting digits.

        if (validPuzzle) { // Skips the search if the puzzle cannot be solved.
            solveRecursive(0); // Searches for every solution from the first cell.
        } // Ends the valid-puzzle check.

        reportResult(validPuzzle); // Prints and saves the final result.

        if (!fileOpened) { // Checks whether there is a file to finish saving.
            return false; // Reports that the solutions were not saved.
        } // Ends the opened-file check.

        solutionFile.close(); // Saves everything to the solution file.

        if (solutionFile.fail()) { // Checks whether any write failed.
            cerr << "Error: Could not write " << outputName << endl; // Prints an error.
            return false; // Reports that solving failed.
        } // Ends the write check.

        return true; // Reports that the solutions were saved.
    } // Ends solve.
}; // Ends the SudokuSolver class.

int main() { // Starts the program.
    const string puzzleFiles[] = { // Lists the five input files.
        "puzzle1.txt", // First Sudoku puzzle.
        "puzzle2.txt", // Second Sudoku puzzle.
        "puzzle3.txt", // Third Sudoku puzzle.
        "puzzle4.txt", // Fourth Sudoku puzzle.
        "puzzle5.txt" // Fifth Sudoku puzzle.
    }; // Ends the filename list.

    int exitCode = 0; // Stays zero only if every puzzle is processed.
    int puzzleNumber = 0; // Numbers the solution files.

    for (const string &puzzleFile : puzzleFiles) { // Processes every listed puzzle.
        puzzleNumber++; // Moves to the next solution file number.
        SudokuSolver solver; // Creates a solver for this puzzle.
        string solutionName = "solution" + to_string(puzzleNumber) + ".txt"; // Builds the output filename.

        if (!solver.loadFromFile(puzzleFile) || !solver.solve(solutionName)) { // Loads, then solves the puzzle.
            remove(solutionName.c_str()); // Deletes any partial or outdated solution file.
            exitCode = 1; // Records the failure and moves on to the next puzzle.
        } // Ends the failure check.
    } // Ends the puzzle loop.

    return exitCode; // Ends the program, reporting any failure.
} // Ends main.
